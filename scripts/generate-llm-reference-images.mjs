// Generates server/reference-images.mjs — a small, server-only bundle of the
// 12 card images (downscaled + JPEG-encoded) that the classification backend
// sends to the vision LLM as ground truth. Lives under server/, never public/,
// so it's never shipped to the browser bundle.
import sharp from 'sharp'
import { readFileSync, writeFileSync } from 'node:fs'

const CONFIG_PATH = 'public/demo-experience.json'
const OUTPUT_PATH = 'server/reference-images.mjs'
const MAX_DIMENSION = 512
const JPEG_QUALITY = 80

async function encodeReference(targetImageUrl) {
  const buffer = await sharp(`public${targetImageUrl}`)
    .resize({ width: MAX_DIMENSION, height: MAX_DIMENSION, fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: JPEG_QUALITY })
    .toBuffer()
  return buffer.toString('base64')
}

async function main() {
  const config = JSON.parse(readFileSync(CONFIG_PATH, 'utf8'))
  const targets = config
    .map((experience, index) => ({ index, targetImageUrl: experience.targetImageUrl, title: experience.cardTitle }))
    .filter((t) => typeof t.targetImageUrl === 'string')

  if (!targets.length) throw new Error('No experiences with targetImageUrl found in ' + CONFIG_PATH)

  const entries = []
  for (const target of targets) {
    const image = await encodeReference(target.targetImageUrl)
    entries.push({ index: target.index, title: target.title, image })
    console.log(`Encoded ${target.targetImageUrl} -> ${target.title} (${(image.length / 1024).toFixed(0)} KiB base64)`)
  }

  const fileContents =
    '// Auto-generated by scripts/generate-llm-reference-images.mjs — do not edit by hand.\n' +
    `export default ${JSON.stringify({ targets: entries })}\n`
  writeFileSync(OUTPUT_PATH, fileContents)
  console.log(`\nWrote ${OUTPUT_PATH} (${entries.length} reference images)`)
}

main().catch((err) => { console.error(err); process.exit(1) })
